// Shapey staging - event-based meme commentary.
//
// What it does (human players only; the AI never triggers or receives a meme):
//   * Every human player has an attempt counter. In every window of 3 attempts one random attempt
//     fires a meme: a LOSE meme when that attempt lost, a WIN meme when it won. Each meme is one
//     random file picked from audio/<win|lose> or gifs/<win|lose>.
//   * Tag: when a team wins, a file from gifs/tag_win is shown at an interval of 4 attempts per player
//     (one random winning attempt in every window of 4). Losses keep the normal 4-attempt lose rule.
//   * Delay: if the player whose turn it is has not picked anything and the pick countdown reaches
//     10 seconds, one file from gifs/delay_pick is shown (once per turn).
//   * A win is a submitted match of 3 or more identical shapes (3, 4, 5+ ...). The game's own match rule
//     (ShapeyRules.isValidMatchSize / MIN_MATCH) decides it; this file only reacts to the result.
//   * Pictures / GIFs appear between the header and the tray. Audio memes are cut off at 5 seconds.
//
// Files live in assets/memes/{audio,gifs}/<folder>/. The browser cannot list a folder, so
// assets/memes/manifest.json is generated by tools/build-memes-manifest.js (CI checks it is current).
// Add ?memes=off to the URL to switch the commentary off.
(function attachShapeyMemes(root, factory) {
  const memes = factory(root);
  if (typeof module === 'object' && module.exports) module.exports = memes;
  if (root) root.ShapeyMemes = memes;
})(typeof globalThis !== 'undefined' ? globalThis : this, function createShapeyMemes(root) {
  'use strict';

  const CONFIG = Object.freeze({
    assetBase: 'assets/memes',
    manifestUrl: 'assets/memes/manifest.json',
    standardWindow: 4,   // one win/lose meme per four attempts, per human player
    tagWinWindow: 4,     // Tag: one team-win meme per this many attempts, per human player
    delayAtMs: 10000,    // Delay meme when this much of an idle player's pick countdown is left
    maxAudioMs: 5000,    // audio memes never play longer than this
    audioFadeMs: 250,    // short fade-out right before the cut-off
    audioVolume: 0.9,
    audioChance: 0.5,    // when a pool has both audio and pictures: audio this often, picture otherwise
    visualMs: 3500,      // how long a picture / GIF stays up
    stage: Object.freeze({ width: 720, height: 1280 }),
    // The strip from just under the header planks (the timer plank ends near y=155) down to the tray's top edge
    // (about y=285), in game (720 x 1280) coordinates. It stays between the two score planks (x 210-510).
    slot: Object.freeze({ x: 360, y: 162, w: 300, h: 122 }),
    maxUpscale: 1.5,     // small GIFs may be enlarged this much to fill the slot
  });

  // Meme kinds -> the manifest folders (normalised: lower case, spaces / dashes / slashes become "_") that feed them.
  const POOL_FOLDERS = Object.freeze({
    win: ['win'],
    lose: ['lose'],
    tagWin: ['tag_win', 'tag_wins', 'tags_win', 'tags_wins'],
    delay: ['delay', 'delay_pick', 'delay_picks'],
  });

  // ------------------------------------------------------------------ pure helpers
  const randomInt = (rng, min, max) => min + Math.floor(rng() * (max - min + 1));

  // Counts one player's attempts in windows of `size`. A random attempt of each window is the trigger.
  // When that attempt does not qualify (for example a loss when only wins may fire), the trigger stays
  // armed and fires on the next qualifying attempt of the same window; otherwise it lapses at the window's end.
  class AttemptWindow {
    constructor(size, rng = Math.random) {
      this.size = size;
      this.rng = rng;
      this.reset();
    }
    reset() {
      this.count = 0;
      this.target = randomInt(this.rng, 1, this.size);
      this.fired = false;
    }
    // Returns true when a meme should fire for this attempt.
    record(qualifies = true) {
      this.count++;
      let fire = false;
      if (!this.fired && this.count >= this.target && qualifies) {
        fire = true;
        this.fired = true;
      }
      if (this.count >= this.size) this.reset();
      return fire;
    }
  }

  // Deals every item once, in random order, before any repeats; never the same item twice in a row.
  class ShuffleBag {
    constructor(items, rng = Math.random) {
      this.items = items.slice();
      this.rng = rng;
      this.queue = [];
      this.last = null;
    }
    refill() {
      const bag = this.items.slice();
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(this.rng() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
      if (bag.length > 1 && bag[bag.length - 1] === this.last) {
        [bag[0], bag[bag.length - 1]] = [bag[bag.length - 1], bag[0]];
      }
      this.queue = bag; // items are dealt from the end
    }
    next() {
      if (!this.items.length) return null;
      if (!this.queue.length) this.refill();
      this.last = this.queue.pop();
      return this.last;
    }
  }

  const folderKey = (name) => String(name).toLowerCase().replace(/[\s\-/\\]+/g, '_');
  const encodePath = (path) => String(path).split('/').map(encodeURIComponent).join('/');

  function collectFiles(group, dir, aliases, base) {
    const out = [];
    for (const [folder, files] of Object.entries(group || {})) {
      if (!aliases.includes(folderKey(folder)) || !Array.isArray(files)) continue;
      for (const file of files) out.push({ name: file, url: [base, dir, encodePath(folder), encodeURIComponent(file)].join('/') });
    }
    return out;
  }

  // manifest = { audio: { <folder>: [files] }, gifs: { <folder>: [files] } }  ->  { kind: { audio: [], visual: [] } }
  function buildPools(manifest, base = CONFIG.assetBase) {
    const pools = {};
    for (const [kind, aliases] of Object.entries(POOL_FOLDERS)) {
      pools[kind] = {
        audio: collectFiles(manifest && manifest.audio, 'audio', aliases, base),
        visual: collectFiles(manifest && manifest.gifs, 'gifs', aliases, base),
      };
    }
    return pools;
  }

  // Picks the next meme for a kind: audio or picture at random (only one of them when the other is empty).
  class MemePicker {
    constructor(pools, rng = Math.random, audioChance = CONFIG.audioChance) {
      this.pools = pools;
      this.rng = rng;
      this.audioChance = audioChance;
      this.bags = new Map();
    }
    pick(kind) {
      const pool = this.pools[kind];
      if (!pool) return null;
      const types = ['audio', 'visual'].filter((type) => pool[type].length > 0);
      if (!types.length) return null;
      const type = types.length === 1 ? types[0] : (this.rng() < this.audioChance ? 'audio' : 'visual');
      const key = kind + ':' + type;
      if (!this.bags.has(key)) this.bags.set(key, new ShuffleBag(pool[type], this.rng));
      const item = this.bags.get(key).next();
      return item ? { kind, type, name: item.name, url: item.url } : null;
    }
  }

  // ------------------------------------------------------------------ manifest library (shared by every scene)
  function createLibrary(options = {}) {
    const rng = options.rng || Math.random;
    const loadManifest = options.loadManifest || (() => {
      if (typeof fetch !== 'function' || typeof document === 'undefined') return Promise.reject(new Error('no fetch'));
      return fetch(new URL(CONFIG.manifestUrl, document.baseURI).href).then((response) => {
        if (!response.ok) throw new Error('HTTP ' + response.status);
        return response.json();
      });
    });
    const library = {
      ready: false,
      picker: null,
      loading: null,
      ensureLoaded() {
        if (!library.loading) {
          library.loading = Promise.resolve().then(loadManifest).then((manifest) => {
            library.picker = new MemePicker(buildPools(manifest), rng);
            library.ready = true;
          }).catch((error) => {
            console.warn('Shapey memes are off: could not load ' + CONFIG.manifestUrl + ' (' + (error && error.message) + ').');
          });
        }
        return library.loading;
      },
      pick(kind) { return library.ready ? library.picker.pick(kind) : null; },
    };
    return library;
  }

  // ------------------------------------------------------------------ browser output (DOM image + HTML audio)
  function createBrowserPlayer(scene) {
    let img = null;
    let imgTimer = null;
    let imgToken = 0;
    let audio = null;
    let audioTimer = null;
    let fadeTimer = null;

    function layout() {
      if (!img || !img.parentNode) return;
      const canvas = scene.game && scene.game.canvas;
      if (!canvas) return;
      const rect = canvas.getBoundingClientRect();
      const scale = rect.width / CONFIG.stage.width;
      const naturalW = img.naturalWidth || 1;
      const naturalH = img.naturalHeight || 1;
      const slot = CONFIG.slot;
      const fit = Math.min(slot.w / naturalW, slot.h / naturalH, CONFIG.maxUpscale);
      const w = naturalW * fit;
      const h = naturalH * fit;
      img.style.width = (w * scale) + 'px';
      img.style.height = (h * scale) + 'px';
      img.style.left = (rect.left + (slot.x - w / 2) * scale) + 'px';
      img.style.top = (rect.top + (slot.y + (slot.h - h) / 2) * scale) + 'px';
    }

    function hideVisual() {
      imgToken++;
      clearTimeout(imgTimer);
      imgTimer = null;
      if (img && img.parentNode) img.parentNode.removeChild(img);
      img = null;
    }

    function showVisual(item) {
      hideVisual();
      const token = imgToken;
      const el = new Image(); // a fresh element restarts an animated GIF / WebP from its first frame
      el.alt = '';
      el.decoding = 'async';
      el.draggable = false;
      Object.assign(el.style, {
        position: 'fixed', zIndex: '9000', pointerEvents: 'none', userSelect: 'none',
        borderRadius: '8px', boxShadow: '0 2px 10px rgba(0,0,0,.55)', background: 'rgba(18,10,5,.35)',
      });
      el.onload = () => {
        if (token !== imgToken) return;
        img = el;
        document.body.appendChild(el);
        layout();
        imgTimer = setTimeout(hideVisual, CONFIG.visualMs);
      };
      el.onerror = () => {};
      el.src = item.url;
    }

    function stopAudio() {
      clearTimeout(audioTimer);
      clearInterval(fadeTimer);
      audioTimer = null;
      fadeTimer = null;
      if (audio) {
        try { audio.pause(); audio.currentTime = 0; } catch (_) { /* already gone */ }
        audio = null;
      }
    }

    function playAudio(item) {
      stopAudio();
      if (typeof Audio !== 'function') return;
      const clip = new Audio(item.url);
      clip.volume = CONFIG.audioVolume;
      audio = clip;
      // The 5 second limit counts from the moment sound actually starts, and is enforced twice:
      // by a timer and by the playback position, so a slow start or a seek can't stretch it.
      const cut = () => { if (audio === clip) stopAudio(); };
      clip.addEventListener('playing', () => {
        if (audio !== clip || audioTimer) return;
        const left = Math.max(0, CONFIG.maxAudioMs - clip.currentTime * 1000);
        audioTimer = setTimeout(cut, left);
        const fadeAt = Math.max(0, left - CONFIG.audioFadeMs);
        setTimeout(() => {
          if (audio !== clip) return;
          const steps = 5;
          let step = 0;
          fadeTimer = setInterval(() => {
            step++;
            try { clip.volume = Math.max(0, CONFIG.audioVolume * (1 - step / steps)); } catch (_) { /* ignore */ }
            if (step >= steps) clearInterval(fadeTimer);
          }, CONFIG.audioFadeMs / steps);
        }, fadeAt);
      });
      clip.addEventListener('timeupdate', () => { if (clip.currentTime * 1000 >= CONFIG.maxAudioMs) cut(); });
      clip.addEventListener('ended', () => { if (audio === clip) stopAudio(); });
      const started = clip.play();
      if (started && typeof started.catch === 'function') started.catch(() => { if (audio === clip) audio = null; }); // autoplay blocked
    }

    return {
      showVisual,
      playAudio,
      hide() { hideVisual(); stopAudio(); },
      layout,
      isVisualVisible: () => Boolean(img),
    };
  }

  // ------------------------------------------------------------------ scene adapter
  const urlOff = () => {
    try { return new URLSearchParams(root.location.search).get('memes') === 'off'; } catch (_) { return false; }
  };

  const sharedLibrary = createLibrary();

  // One per GameScene. `options.library` / `options.player` / `options.rng` exist so tests can run without a browser.
  function attach(scene, options = {}) {
    const library = options.library || sharedLibrary;
    const rng = options.rng || Math.random;
    const player = options.player || createBrowserPlayer(scene);
    const disabled = options.disabled !== undefined ? options.disabled : urlOff();
    library.ensureLoaded();

    const schedulers = new Map();   // player key -> { standard, tag }
    let activityKey = null;         // the turn in which a human last picked a tile
    let delayShownKey = null;       // the turn that already had its Delay meme
    let resolvedKey = null;         // online: the last turn whose result was handled
    let baseKey = null;             // online: turn whose starting scores are remembered
    let baseScores = [];

    const enabled = () => !disabled && !scene.spectator && library.ready;
    const isTag = () => Boolean(scene.modeCfg && scene.modeCfg.teams);

    const onlineTurnKey = (state) => 'o' + state.turnIndex + ':' + state.activePlayerNumber + ':' + (state.isBonusTurn ? 1 : 0);
    const turnKey = () => (scene.online
      ? (scene.onlineState ? onlineTurnKey(scene.onlineState) : null)
      : 'l' + scene.turnId);

    function schedulersFor(playerKey) {
      if (!schedulers.has(playerKey)) {
        schedulers.set(playerKey, {
          standard: new AttemptWindow(CONFIG.standardWindow, rng),
          tag: new AttemptWindow(CONFIG.tagWinWindow, rng),
        });
      }
      return schedulers.get(playerKey);
    }

    function play(kind) {
      const item = library.pick(kind);
      if (!item) return;
      if (item.type === 'audio') {
        if (scene.sound && scene.sound.mute) return; // respect a muted game
        player.playAudio(item);
      } else {
        player.showVisual(item);
      }
    }

    // One finished attempt of one human player.
    function attempt(playerKey, outcome) {
      if (!enabled()) return;
      const win = outcome === 'win';
      const tag = isTag();
      const sched = schedulersFor(playerKey);
      // Every attempt counts in both windows. In Tag a win belongs to the 4-attempt team-win window only,
      // so it must not use up the 3-attempt slot that the next loss may still take.
      const standardFire = sched.standard.record(!(tag && win));
      const tagFire = tag ? sched.tag.record(win) : false;
      if (tag && win) {
        if (tagFire) play('tagWin');
      } else if (standardFire) {
        play(win ? 'win' : 'lose');
      }
    }

    const controller = {
      // A human tapped a tile: they are taking part in this turn.
      noteActivity() { activityKey = turnKey(); },

      // Local games: a finished attempt of the player whose turn it is (Play Alone's wrong shapes / too-small submits).
      attemptResult(outcome) {
        if (scene.online || scene.isAITurn()) return;
        attempt('p' + scene.limiterSlot(), outcome);
      },

      // Local games: endTurn() reason -> attempt result. 'match' is a win; everything else that ended a turn
      // in which something was picked is a loss. A turn with no pick at all is not an attempt.
      turnResult(reason) {
        if (scene.online || scene.isAITurn()) return;
        if (activityKey !== turnKey()) return;
        attempt('p' + scene.limiterSlot(), reason === 'match' ? 'win' : 'lose');
      },

      // Online games: the server does not announce results, so read them from consecutive snapshots.
      onlineState(previous, next) {
        if (!scene.online || !next || next.status === 'study') return;
        const key = onlineTurnKey(next);
        if (previous && previous.status === 'playing' && next.status === 'playing') {
          const prevKey = onlineTurnKey(previous);
          if (prevKey !== key && resolvedKey !== prevKey) {
            resolvedKey = prevKey;
            const side = previous.activeSide;
            const before = Number((baseKey === prevKey ? baseScores : previous.scores || [])[side]) || 0;
            const after = Math.max(Number((previous.scores || [])[side]) || 0, Number((next.scores || [])[side]) || 0);
            const won = after > before;
            if (won || activityKey === prevKey) attempt('p' + ((Number(previous.activePlayerNumber) || 1) - 1), won ? 'win' : 'lose');
          }
        }
        if (baseKey !== key) {
          baseKey = key;
          baseScores = Array.isArray(next.scores) ? next.scores.slice() : [];
        }
        // Another player's picks show up as selected tiles in the server snapshot.
        if (next.status === 'playing' && Array.isArray(next.tiles) && next.tiles.some((tile) => tile && tile.selected)) activityKey = key;
      },

      // Runs every frame: keeps the picture on the canvas and fires the Delay meme.
      tick() {
        if (player.isVisualVisible()) player.layout();
        if (!enabled() || scene.gameOver || scene.turnEnding || !scene.modeCfg || !scene.modeCfg.turnClock) return;
        const key = turnKey();
        if (!key || delayShownKey === key || activityKey === key) return;
        if (scene.online) {
          const state = scene.onlineState;
          if (!state || state.status !== 'playing' || state.pendingEffect) return;
        } else {
          if (scene.isAITurn()) return;
          if (Number.isFinite(scene.openingReviewEndsAt) && scene.openingReviewEndsAt > Date.now()) return; // still studying
        }
        const total = scene.currentTurnDurationMs || scene.turnDurationMs;
        const left = Math.min(total, scene.turnClock.remaining()); // the same number the timer plank shows
        if (!Number.isFinite(left) || left <= 0 || left > CONFIG.delayAtMs) return;
        delayShownKey = key;
        play('delay');
      },

      visualVisible: () => player.isVisualVisible(),
      hide() { player.hide(); },
      destroy() { player.hide(); },
    };

    if (scene.events && typeof scene.events.once === 'function') {
      scene.events.once('shutdown', controller.destroy);
      scene.events.once('destroy', controller.destroy);
    }
    return controller;
  }

  return {
    CONFIG,
    POOL_FOLDERS,
    AttemptWindow,
    ShuffleBag,
    MemePicker,
    buildPools,
    createLibrary,
    createBrowserPlayer,
    attach,
  };
});
